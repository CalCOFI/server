-- ── immutability guard (file, scan) ─────────────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION ctd.no_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF coalesce(current_setting('ctd.allow_mutation', true), 'off') <> 'on' THEN
    RAISE EXCEPTION 'ctd.% is immutable (originals are never edited — record a flag in ctd.flag). Admins: SET ctd.allow_mutation = on; to override deliberately.', TG_TABLE_NAME
      USING ERRCODE = 'insufficient_privilege';
  END IF;
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS file_immutable ON ctd.file;
CREATE TRIGGER file_immutable BEFORE UPDATE OR DELETE ON ctd.file FOR EACH ROW EXECUTE FUNCTION ctd.no_mutation();
DROP TRIGGER IF EXISTS scan_immutable ON ctd.scan;
CREATE TRIGGER scan_immutable BEFORE UPDATE OR DELETE ON ctd.scan FOR EACH ROW EXECUTE FUNCTION ctd.no_mutation();
DROP TRIGGER IF EXISTS file_no_truncate ON ctd.file;
CREATE TRIGGER file_no_truncate BEFORE TRUNCATE ON ctd.file FOR EACH STATEMENT EXECUTE FUNCTION ctd.no_mutation();
DROP TRIGGER IF EXISTS scan_no_truncate ON ctd.scan;
CREATE TRIGGER scan_no_truncate BEFORE TRUNCATE ON ctd.scan FOR EACH STATEMENT EXECUTE FUNCTION ctd.no_mutation();

