-- ── ctd.flag — the ledger ───────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS ctd.flag (
  flag_id        bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  scan_id        bigint REFERENCES ctd.scan(scan_id),       -- NULL => file/cast-level flag
  file_id        int    REFERENCES ctd.file(file_id),       -- required when scan_id is NULL
  variable       text   NOT NULL,                           -- a ctd.scan column name, or '*' for the whole row/file
  qual_code      smallint NOT NULL REFERENCES ctd.qual_code(qual_code),
  proposed_value double precision,                          -- the corrected value (qual_code 5), else NULL
  rule_key       text,                                      -- set when a QC rule proposed it (workflows metadata/qc_rules)
  reason         text,
  status         text NOT NULL DEFAULT 'proposed' CHECK (status IN ('proposed','accepted','rejected','withdrawn')),
  created_by     text NOT NULL DEFAULT current_user,
  created_at     timestamptz NOT NULL DEFAULT now(),
  reviewed_by    text,
  reviewed_at    timestamptz,
  review_note    text,
  CHECK (scan_id IS NOT NULL OR file_id IS NOT NULL)   -- variable validity is enforced by ctd.flag_guard()
);
COMMENT ON TABLE ctd.flag IS 'QA/QC ledger: one row per (scan or file) × variable × proposal. Anyone proposes; curators accept/reject; history in ctd.flag_audit.';
CREATE INDEX IF NOT EXISTS flag_scan_idx   ON ctd.flag (scan_id, variable) WHERE scan_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS flag_file_idx   ON ctd.flag (file_id) WHERE file_id IS NOT NULL;
