CREATE UNIQUE INDEX IF NOT EXISTS flag_one_accepted_per_cell ON ctd.flag (scan_id, variable) WHERE status = 'accepted' AND scan_id IS NOT NULL;

-- validation + review bookkeeping
CREATE OR REPLACE FUNCTION ctd.flag_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.variable <> '*' AND NOT EXISTS (SELECT 1 FROM ctd.scan_column WHERE column_name = NEW.variable) THEN
    RAISE EXCEPTION 'variable "%" is not a ctd.scan column (see ctd.scan_column) — use ''*'' for the whole row', NEW.variable;
  END IF;
  IF NEW.qual_code = 5 AND NEW.proposed_value IS NULL THEN
    RAISE EXCEPTION 'qual_code 5 (changed) needs a proposed_value';
  END IF;
  IF NEW.scan_id IS NOT NULL AND NEW.file_id IS NULL THEN
    SELECT file_id INTO NEW.file_id FROM ctd.scan WHERE scan_id = NEW.scan_id;
  END IF;
  IF TG_OP = 'INSERT' THEN
    NEW.created_by := current_user; NEW.created_at := now();
    NEW.status := 'proposed'; NEW.reviewed_by := NULL; NEW.reviewed_at := NULL;
  ELSE
    -- the target cell is fixed once proposed
    IF NEW.scan_id IS DISTINCT FROM OLD.scan_id OR NEW.file_id IS DISTINCT FROM OLD.file_id OR NEW.variable <> OLD.variable THEN
      RAISE EXCEPTION 'cannot move a flag to another scan/variable — withdraw it and propose a new one';
    END IF;
    NEW.created_by := OLD.created_by; NEW.created_at := OLD.created_at;
    IF NEW.status <> OLD.status THEN
      IF NEW.status IN ('accepted','rejected') THEN
        IF NOT pg_has_role(current_user, 'calcofi_curator', 'MEMBER') THEN
          RAISE EXCEPTION 'only calcofi_curator members may accept/reject (you can withdraw your own proposal)';
        END IF;
        NEW.reviewed_by := current_user; NEW.reviewed_at := now();
      ELSIF NEW.status = 'withdrawn' THEN
        IF OLD.created_by <> current_user AND NOT pg_has_role(current_user, 'calcofi_curator', 'MEMBER') THEN
          RAISE EXCEPTION 'only the proposer (or a curator) may withdraw';
        END IF;
      ELSIF NEW.status = 'proposed' THEN
        NEW.reviewed_by := NULL; NEW.reviewed_at := NULL;   -- re-opened by a curator
      END IF;
    END IF;
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS flag_guard ON ctd.flag;
CREATE TRIGGER flag_guard BEFORE INSERT OR UPDATE ON ctd.flag FOR EACH ROW EXECUTE FUNCTION ctd.flag_guard();

-- audit trail
CREATE TABLE IF NOT EXISTS ctd.flag_audit (
  audit_id  bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  flag_id   bigint NOT NULL,
  op        text NOT NULL,
  at        timestamptz NOT NULL DEFAULT now(),
  by_role   text NOT NULL DEFAULT current_user,
  old_row   jsonb,
  new_row   jsonb
);
-- SECURITY DEFINER: the proposer has no INSERT on flag_audit (append-only by design); the owner writes it
CREATE OR REPLACE FUNCTION ctd.flag_audit_fn() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = ctd, public AS $$
BEGIN
  -- session_user = the person who logged in (inside SECURITY DEFINER current_user is the owner)
  INSERT INTO ctd.flag_audit (flag_id, op, by_role, old_row, new_row)
  VALUES (coalesce(NEW.flag_id, OLD.flag_id), TG_OP, session_user,
          CASE WHEN TG_OP <> 'INSERT' THEN to_jsonb(OLD) END,
          CASE WHEN TG_OP <> 'DELETE' THEN to_jsonb(NEW) END);
  RETURN NULL;
END $$;
DROP TRIGGER IF EXISTS flag_audit ON ctd.flag;
CREATE TRIGGER flag_audit AFTER INSERT OR UPDATE OR DELETE ON ctd.flag FOR EACH ROW EXECUTE FUNCTION ctd.flag_audit_fn();

