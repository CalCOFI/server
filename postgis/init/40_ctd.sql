-- ── derived: best stage per study, cast headers ─────────────────────────────────────────────
CREATE OR REPLACE VIEW ctd.v_file_best AS
  SELECT f.* FROM ctd.file f WHERE f.is_best_stage;
COMMENT ON VIEW ctd.v_file_best IS 'ctd.file restricted to the best data stage available per study (final > preliminary_with_bottle > preliminary_without_bottle).';

CREATE OR REPLACE VIEW ctd.v_scan_best AS
  SELECT s.* FROM ctd.scan s JOIN ctd.file f USING (file_id) WHERE f.is_best_stage;
COMMENT ON VIEW ctd.v_scan_best IS 'ctd.scan for the best data stage per study only — what most analyses want. Superseded prelim files stay in ctd.scan for comparison.';

CREATE MATERIALIZED VIEW IF NOT EXISTS ctd.cast AS
  SELECT
    f.file_id, f.study, f.cruise_key, f.data_stage, f.cast_dir, f.is_best_stage,
    s.cast_id,
    min(s.ord_occ)        AS ord_occ,
    min(s.sta_id)         AS sta_id,
    min(s.line)           AS line,
    min(s.sta)            AS sta,
    min(s.date_time_utc)  AS datetime_utc,
    avg(s.lat_dec)        AS lat,
    avg(s.lon_dec)        AS lon,
    count(*)              AS n_scans,
    min(s.depth)          AS depth_min,
    max(s.depth)          AS depth_max,
    CASE WHEN avg(s.lon_dec) IS NOT NULL AND avg(s.lat_dec) IS NOT NULL
         THEN ST_SetSRID(ST_MakePoint(avg(s.lon_dec), avg(s.lat_dec)), 4326) END AS geom
  FROM ctd.scan s JOIN ctd.file f USING (file_id)
  GROUP BY f.file_id, f.study, f.cruise_key, f.data_stage, f.cast_dir, f.is_best_stage, s.cast_id
WITH NO DATA;
CREATE UNIQUE INDEX IF NOT EXISTS cast_pk ON ctd.cast (file_id, cast_id);
CREATE INDEX IF NOT EXISTS cast_geom_idx ON ctd.cast USING gist (geom);
COMMENT ON MATERIALIZED VIEW ctd.cast IS 'One row per cast per file, from the scan header columns (immutable by construction: derived from ctd.scan). Refresh with ctd.refresh_derived().';

-- ── generated QC views: <var>_qc / <var>_fix beside every measurement column ────────────────
-- One aggregated pivot of the ACCEPTED flags (ctd.v_flag_accepted_wide: one row per scan_id with
-- <col>_qc / <col>_fix), LEFT JOINed once onto v_scan_best. Regenerate with ctd.build_qc_views()
-- (called by ctd.refresh_derived()) if ctd.scan_column changes.
CREATE OR REPLACE FUNCTION ctd.build_qc_views() RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ctd, public AS $$
DECLARE
  mcols text[];   -- measurement + bottle columns (flaggable, fixable)
  allcols text[]; -- every scan column in ordinal order
  pivot text; qc_cols text; clean_cols text; joins text;
BEGIN
  SELECT array_agg(column_name ORDER BY ordinal) INTO mcols   FROM ctd.scan_column WHERE kind IN ('measurement','bottle');
  SELECT array_agg(column_name ORDER BY ordinal) INTO allcols FROM ctd.scan_column;
  IF mcols IS NULL THEN RAISE NOTICE 'ctd.scan_column is empty — nothing to build'; RETURN; END IF;

  SELECT string_agg(format(
           ', max(qual_code) FILTER (WHERE variable = %1$L) AS %2$I, max(proposed_value) FILTER (WHERE variable = %1$L) AS %3$I',
           c, c || '_qc', c || '_fix'), '' ORDER BY o)
    INTO pivot FROM unnest(mcols) WITH ORDINALITY AS t(c, o);
  SELECT string_agg(format(', w.%1$I, w.%2$I', c || '_qc', c || '_fix'), '' ORDER BY o)
    INTO qc_cols FROM unnest(mcols) WITH ORDINALITY AS t(c, o);
  SELECT string_agg(
           CASE WHEN c = ANY (mcols) THEN
             format(', CASE WHEN w.%2$I IS NOT NULL THEN w.%2$I WHEN coalesce(q%3$s.is_bad, false) THEN NULL ELSE s.%1$I END AS %1$I', c, c || '_fix', o)
           ELSE format(', s.%I', c) END, '' ORDER BY o)
    INTO clean_cols FROM unnest(allcols) WITH ORDINALITY AS t(c, o);
  SELECT string_agg(format(' LEFT JOIN ctd.qual_code q%1$s ON q%1$s.qual_code = w.%2$I', o, c || '_qc'), '' ORDER BY o)
    INTO joins FROM unnest(allcols) WITH ORDINALITY AS t(c, o) WHERE c = ANY (mcols);

  EXECUTE 'DROP VIEW IF EXISTS ctd.v_scan_clean';
  EXECUTE 'DROP VIEW IF EXISTS ctd.v_scan_qc';
  EXECUTE 'DROP VIEW IF EXISTS ctd.v_flag_accepted_wide';
  EXECUTE 'CREATE VIEW ctd.v_flag_accepted_wide AS SELECT scan_id' || pivot ||
          ' FROM ctd.flag WHERE status = ' || quote_literal('accepted') || ' AND scan_id IS NOT NULL GROUP BY scan_id';
  EXECUTE 'COMMENT ON VIEW ctd.v_flag_accepted_wide IS ' || quote_literal('Accepted flags pivoted to one row per scan: <col>_qc (IODE code) and <col>_fix (corrected value). Generated by ctd.build_qc_views().');
  EXECUTE 'CREATE VIEW ctd.v_scan_qc AS SELECT s.*' || qc_cols ||
          ' FROM ctd.v_scan_best s LEFT JOIN ctd.v_flag_accepted_wide w USING (scan_id)';
  EXECUTE 'COMMENT ON VIEW ctd.v_scan_qc IS ' || quote_literal('ctd.v_scan_best plus <col>_qc / <col>_fix for every measurement column, from ACCEPTED flags. Generated by ctd.build_qc_views().');
  EXECUTE 'CREATE VIEW ctd.v_scan_clean AS SELECT s.scan_id, s.file_id, s.row_num' || clean_cols ||
          ' FROM ctd.v_scan_best s LEFT JOIN ctd.v_flag_accepted_wide w USING (scan_id)' || joins;
  EXECUTE 'COMMENT ON VIEW ctd.v_scan_clean IS ' || quote_literal('ctd.v_scan_best with accepted fixes substituted and accepted is_bad flags nulled — the clean series. Generated by ctd.build_qc_views().');
  EXECUTE 'GRANT SELECT ON ctd.v_flag_accepted_wide, ctd.v_scan_qc, ctd.v_scan_clean TO calcofi_reader';
END $$;

CREATE OR REPLACE FUNCTION ctd.refresh_derived() RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ctd, public AS $$
BEGIN
  -- best-stage flags, recomputed from what is loaded (final > preliminary_with_bottle > preliminary_without_bottle).
  -- This is the one sanctioned UPDATE on ctd.file; it is a derived column, not source data.
  PERFORM set_config('ctd.allow_mutation', 'on', true);
  UPDATE ctd.file f SET is_best_stage = (f.data_stage = b.best)
  FROM (SELECT study, (array_agg(data_stage ORDER BY array_position(ARRAY['final','preliminary_with_bottle','preliminary_without_bottle'], data_stage)))[1] AS best
        FROM ctd.file GROUP BY study) b
  WHERE f.study = b.study AND f.is_best_stage IS DISTINCT FROM (f.data_stage = b.best);
  PERFORM set_config('ctd.allow_mutation', 'off', true);
  IF EXISTS (SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
             WHERE n.nspname = 'ctd' AND c.relname = 'cast' AND c.relkind = 'm' AND c.relispopulated) THEN
    REFRESH MATERIALIZED VIEW CONCURRENTLY ctd.cast;
  ELSE
    REFRESH MATERIALIZED VIEW ctd.cast;
  END IF;
  PERFORM ctd.build_qc_views();
END $$;
COMMENT ON FUNCTION ctd.refresh_derived() IS 'After a load: recompute ctd.file.is_best_stage, refresh ctd.cast, regenerate the QC views.';
GRANT EXECUTE ON FUNCTION ctd.refresh_derived() TO calcofi_loader;
GRANT EXECUTE ON FUNCTION ctd.build_qc_views() TO calcofi_loader;

RESET ROLE;
