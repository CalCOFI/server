-- 40_ctd.sql — the CTD archive in PostgreSQL: originals immutable, flags beside, products on top.
--   docker exec -i postgis psql -U admin -d calcofi -v ON_ERROR_STOP=1 -f /share/github/CalCOFI/server/postgis/init/40_ctd.sql
-- Idempotent (CREATE IF NOT EXISTS / OR REPLACE). Run as superuser; objects are owned by calcofi_admin.
--
-- Design (plan 2026-08-17 WS8, decisions D7/D8):
--   ctd.file         one row per source file (archive member), sha256, stage, cruise — IMMUTABLE
--   ctd.scan         one row per scan line, EVERY source column verbatim (82 columns of the
--                    calcofi.org db-CSV products, lower-cased), + file_id/row_num provenance — IMMUTABLE
--   ctd.scan_column  what each column is (source header, description, units) — the data dictionary
--   ctd.qual_code    the flag vocabulary used in ctd.flag (IODE/SeaDataNet primary flags 0–9);
--   ctd.source_qual_code  the source's own *Q column codes (0,1,2,8,9), for reference
--   ctd.flag         the ledger: (scan|file) × variable × proposal; status proposed→accepted|rejected|withdrawn;
--                    row-level security (propose = anyone, review = curators), audit-trailed
--   ctd.flag_audit   append-only copy of every change to ctd.flag
--   ctd.cast         MATERIALIZED: one row per physical cast per file, from the header columns
--   ctd.v_scan_best  scans of the best data stage per cruise (final > prelim_with_bottle > prelim_without_bottle)
--   ctd.v_scan_qc    v_scan_best + <var>_qc / <var>_fix columns from ACCEPTED flags (generated by ctd.build_qc_views())
--   ctd.v_scan_clean v_scan_best with accepted-bad -> NULL and accepted-fix substituted
--   ctd.refresh_derived()  REFRESH the materialized products after a load
--
-- Immutability: calcofi_loader may INSERT into file/scan; nobody UPDATEs/DELETEs them — a trigger
-- raises unless `SET ctd.allow_mutation = on` (a deliberate, logged admin act). Fixes are flags.

SET ROLE calcofi_admin;

